void pawn_sheet(void) {
    u8 r;
    for (r = 0; r < 8; r++) {
        vdp_write_addr17(1, (u16)((200u + r) * 128u));
        vdp_out_block(24, sheet[r]);
        vdp_write_addr17(1, (u16)((200u + r) * 128u + WALK_X / 2));
        vdp_out_block(10, walk[r]);
    }
}

