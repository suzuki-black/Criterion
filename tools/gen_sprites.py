def pat(name, art):
    rows = [r.strip() for r in art.strip('\n').split('\n')]
    rows = [r.ljust(16, '.')[:16] for r in rows] + ['.' * 16] * (16 - len(rows))
    assert len(rows) == 16, name
    PATS[name] = rows

