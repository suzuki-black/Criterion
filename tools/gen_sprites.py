import sys

PATS = {}

def pat(name, art):
    rows = [r.strip() for r in art.strip('\n').split('\n')]
    rows = [r.ljust(16, '.')[:16] for r in rows] + ['.' * 16] * (16 - len(rows))
    assert len(rows) == 16, name
    PATS[name] = rows

def pair(name, a, b):
    """G_PAIR の 2 枚(name = 下の層、name_B = 上の層。パターン番号が続く)。a, b は 16 行の '#' / '.'"""
    PATS[name] = a
    PATS[name + '_B'] = b

def grid(rows):
    return [[c in '#X' for c in r] for r in rows]

def rows_of(g):
    return [''.join('#' if v else '.' for v in r) for r in g]

