def to_bytes(rows):
    out = []
    for qx, qy in ((0, 0), (0, 8), (8, 0), (8, 8)):   # 左上, 左下, 右上, 右下
        for y in range(8):
            b = 0
            for x in range(8):
                if rows[qy + y][qx + x] in '#X':
                    b |= 0x80 >> x
            out.append(b)
    return out

