def needle32():
    """32x32 の回転計の針(右向き。中心の軸から右へ 15 ドット)。ROTOR の元"""
    out = bytearray()
    for y in range(32):
        row = 0
        for x in range(32):
            dx, dy = x - 15.5, y - 15.5
            on = (dx * dx + dy * dy < 12) or (0 <= dx < 15.5 and abs(dy) < 1.6 - dx / 14)
            row = (row << 1) | (1 if on else 0)
        out += row.to_bytes(4, 'big')
    return bytes(out)

def inf32():
    """32x32 の ∞(レムニスケート r^2 = a^2 cos 2θ の太線)。ROTOR(スプライト用)の元。1 行 4 バイト"""
    import math
    pts = []
    for k in range(720):
        t = k / 720 * 2 * math.pi
        d = 1 + math.sin(t) ** 2
        pts.append((15.5 + 14.0 * math.cos(t) / d, 15.5 + 14.0 * math.sin(t) * math.cos(t) / d * 1.6))
    out = bytearray()
    for y in range(32):
        row = 0
        for x in range(32):
            on = min((px - x) ** 2 + (py - y) ** 2 for px, py in pts) < 2.6
            row = (row << 1) | (1 if on else 0)
        out += row.to_bytes(4, 'big')
    return bytes(out)

